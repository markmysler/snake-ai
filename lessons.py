# ---- what a run records about the machine ------------------------------------------------
def recorded_machine(system_info):
    """The machine facts that matter for comparing results (wall-clock speed), nothing identifying."""
    s = system_info or {}
    return {"cpus": s.get("cpus", s.get("cpu_count")), "on_battery": s.get("on_battery")}


def recorded_plan(plan):
    """How the run used the machine: cores per agent and the settings actually used (the planner can
    shrink e.g. a DQN replay buffer to fit in memory, which changes the experiment)."""
    if not plan:
        return None
    return {"parallel": plan.get("parallel"), "cores_per_run": plan.get("cores_per_run"),
            "agents": {aid: {k: a[k] for k in ("algorithm", "cores", "flag", "params") if k in a}
                       for aid, a in (plan.get("agents") or {}).items()}}


def scrub_info(raw):
    """A run.json without machine-specific details (see recorded_machine / recorded_plan)."""
    out = {k: v for k, v in raw.items() if k not in ("live_dir", "pid")}
    if raw.get("status") in ACTIVE and raw.get("pid"):
        out["pid"] = raw["pid"]  # still needed to tell a training run from a dead one
    if "machine" in raw:
        out["machine"] = recorded_machine(raw["machine"])
    if raw.get("plan"):
        out["plan"] = recorded_plan(raw["plan"])
    if isinstance(raw.get("config"), dict) and "imported_from" in raw["config"]:  # folders on the importing machine
        out["config"] = {k: v for k, v in raw["config"].items() if k != "imported_from"}
    return out


def scrub(verbose=True):
    """Rewrite every recorded file without machine-specific details. Returns the files changed."""
    changed = []
    paths = glob.glob(os.path.join(LESSONS_DIR, "*", "runs", "*", "run.json"))
    for path in paths:
        raw = read_json(path)
        if raw and scrub_info(raw) != raw:
            write_json(path, scrub_info(raw))
            changed.append(path)
    for path in glob.glob(os.path.join(LESSONS_DIR, "*", "runs", "*", "analysis.json")):
        raw = read_json(path)
        if raw and raw.get("state") != "running" and "pid" in raw:
            write_json(path, {k: v for k, v in raw.items() if k != "pid"})
            changed.append(path)
    if verbose:
        for path in changed:
            print("scrubbed", os.path.relpath(path, LESSONS_DIR))
    return changed


def new_run(config, status="queued", parallel=1, **extra):
    """Create lessons/<lesson>/runs/<timestamp>/ for a normalized config; returns the run dir."""
    lesson = config["lesson"]
    base = time.strftime("%Y-%m-%d_%H%M%S")
    rid, n = base, 2
    while os.path.exists(os.path.join(LESSONS_DIR, lesson, "runs", rid)):
        rid, n = f"{base}-{n}", n + 1
    run_dir = os.path.join(LESSONS_DIR, lesson, "runs", rid)
    for sub in ("results", "models", "logs"):
        os.makedirs(os.path.join(run_dir, sub))
    write_json(os.path.join(run_dir, "run.json"), {
        "lesson": lesson, "run_id": rid, "name": config.get("name") or "", "note": config.get("note") or "",
        "status": status, "created": time.strftime("%Y-%m-%d %H:%M:%S"), "parallel": parallel,
        "config": config, **extra})
    ensure_lesson(lesson)
    return run_dir


def new_group(config, seeds=1, status="queued", parallel=1, **extra):
    """Queue the same recipe with `seeds` different seeds (seed, seed+1, ...) as a seed group, so the
    spread across seeds shows how much of a result is luck. Returns the run dirs (one if seeds == 1)."""
    seeds = max(1, min(int(seeds or 1), MAX_SEEDS))
    if seeds == 1:
        return [new_run(config, status, parallel, **extra)]
    dirs, group_id, base = [], None, config["seed"]
    for i in range(seeds):
        meta = {"index": i, "size": seeds, "base_seed": base}
        run_dir = new_run({**config, "seed": base + i}, status, parallel, group={**meta, "id": group_id}, **extra)
        if group_id is None:  # the group is named after its first run
            group_id = f"{config['lesson']}/{os.path.basename(run_dir)}"
            update_run(run_dir, group={**meta, "id": group_id})
        dirs.append(run_dir)
    return dirs


def spread(values):
    """n, mean, sample std, min, max of a list of numbers (std is None for a single value)."""
    n = len(values)
    if not n:
        return None
    mean = sum(values) / n
    std = (sum((v - mean) ** 2 for v in values) / (n - 1)) ** 0.5 if n > 1 else None
    return {"n": n, "mean": mean, "std": std, "min": min(values), "max": max(values), "values": values}


def group_members(group_id, runs=None):
    runs = list_runs() if runs is None else runs
    return sorted((r for r in runs if (r.get("group") or {}).get("id") == group_id), key=lambda r: r["group"]["index"])


def group_spread(members):
    """Per agent: the spread of the test mean across the group's evaluated runs."""
    out = {}
    for m in members:
        for aid, ev in (m.get("evaluation") or {}).items():
            out.setdefault(aid, []).append(ev["mean"])
    return {aid: spread(v) for aid, v in out.items()}


def read_run(run_dir):
    """run.json with a normalized config (older runs are translated), plus id and path."""
    info = read_json(os.path.join(run_dir, "run.json"))
    if not info:
        return None
    config = info.get("config", {})
    info["config"] = runconfig.normalize(config) if "agents" in config else runconfig.legacy(config)
    info["config"]["lesson"] = info["lesson"]
    info.setdefault("name", "")
    info.setdefault("note", info["config"].get("note", ""))
    info["id"] = f"{info['lesson']}/{info['run_id']}"
    info["path"] = run_dir
    if info.get("status") == "running" and not system.pid_alive(info.get("pid")):
        info["status"] = "interrupted"  # the process died without recording an end
    return info


def update_run(run_dir, **fields):
    info = read_json(os.path.join(run_dir, "run.json"), {})
    info.update(fields)
    write_json(os.path.join(run_dir, "run.json"), info)
    return info


def list_runs():
    runs = []
    for path in sorted(glob.glob(os.path.join(LESSONS_DIR, "*", "runs", "*", "run.json"))):
        info = read_run(os.path.dirname(path))
        if info:
            runs.append(info)
    return runs


def edit_run(run_id, name=None, note=None, lesson=None):
    """Rename / re-describe a run, or move it to another lesson. Returns the (new) id."""
    run_dir = run_path(run_id)
    info = read_run(run_dir)
    fields = {k: v.strip() for k, v in (("name", name), ("note", note)) if v is not None}
    if fields:
        update_run(run_dir, **fields)
    new_lesson = runconfig.slug(lesson) if lesson else info["lesson"]
    if new_lesson != info["lesson"]:
        if info["status"] in ACTIVE:
            raise ValueError("stop the run before moving it to another lesson")
        dest = os.path.join(LESSONS_DIR, new_lesson, "runs", info["run_id"])
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        shutil.move(run_dir, dest)
        raw = read_json(os.path.join(dest, "run.json"))
        raw["lesson"] = new_lesson
        raw.setdefault("config", {})["lesson"] = new_lesson
        write_json(os.path.join(dest, "run.json"), raw)
        ensure_lesson(new_lesson)
        update_lesson(info["lesson"])
    update_lesson(new_lesson)
    write_index()
    return f"{new_lesson}/{info['run_id']}"


def delete_run(run_id):
    run_dir = run_path(run_id)
    info = read_run(run_dir)
    if info is None:
        raise FileNotFoundError(run_id)
    if info["status"] in ACTIVE:
        raise ValueError("stop the run before deleting it")
    shutil.rmtree(run_dir)
    shutil.rmtree(live_dir(info["id"]), ignore_errors=True)
    forget_run(info["id"])
    lesson_dir = os.path.join(LESSONS_DIR, info["lesson"])
    if not glob.glob(os.path.join(lesson_dir, "runs", "*", "run.json")) and lesson_untouched(info["lesson"]):
        shutil.rmtree(lesson_dir)  # nothing left and nothing written by hand
    else:
        update_lesson(info["lesson"])
    write_index()


def forget_run(run_id):
    """Remove links to a deleted run, keeping what they said: runs it recommended keep the recommendation
    (without the link), "launched as" lists drop it, and ideas it proposed say their source was deleted."""
    for path in glob.glob(os.path.join(LESSONS_DIR, "*", "runs", "*", "run.json")):
        raw = read_json(path)
        if raw and (raw.get("parent") or {}).get("run") == run_id:
            raw["parent"] = {**raw["parent"], "run": None, "deleted": True}
            write_json(path, raw)
    for path in glob.glob(os.path.join(LESSONS_DIR, "*", "runs", "*", "analysis.json")):
        raw = read_json(path)
        recs = (raw or {}).get("recommendations") or []
        if any(run_id in r.get("launched", []) for r in recs):
            for r in recs:
                r["launched"] = [x for x in r.get("launched", []) if x != run_id]
            write_json(path, raw)
    import ideas  # (ideas imports lessons)
    items = ideas.load()
    if any(i["source"].get("run") == run_id for i in items):
        for i in items:
            if i["source"].get("run") == run_id:
                i["source"] = {**i["source"], "run": None, "deleted": True}
        ideas.save(items)


def lesson_untouched(lesson):
    """True if LESSON.md is still the template (so deleting it loses nothing you wrote)."""
    try:
        with open(os.path.join(LESSONS_DIR, lesson, "LESSON.md"), encoding="utf-8") as f:
            text = f.read()
    except OSError:
        return True
    head, _, rest = strip_analysis(text).partition(START)
    template_head, _, template_rest = TEMPLATE.format(lesson=lesson, start=START, end=END).partition(START)
    return head == template_head and rest[rest.find(END):] == template_rest[template_rest.find(END):]


def final_stats(run_dir, agents):
    """Last stats row of each agent's CSV."""
    out = {}
    for a in agents:
        try:
            with open(os.path.join(run_dir, "results", f"{a['id']}.csv"), newline="") as f:
                rows = list(csv.DictReader(f))
        except OSError:
            continue
        if rows:
            r = rows[-1]
            out[a["id"]] = {"iteration_label": r["iteration_label"], "iteration": int(r["iteration"]),
                            "total_steps": int(r["total_steps"]), "total_games": int(r["total_games"]),
                            "elapsed_s": float(r["elapsed_s"]), "best_score": int(r["best_score"]),
                            "mean_score_100": float(r["mean_score_100"])}
    return out


EVAL_KEYS = ("games", "mean", "median", "max", "mean_steps", "median_steps", "steps_per_apple", "outcomes", "per_game")


def backfill(verbose=True):
    """Re-test saved models of runs recorded before per-game outcomes were stored. The test games use
    fixed seeds, so mean / median / max come out the same; a difference is reported."""
    changed = set()
    for info in list_runs():
        ev = info.get("evaluation") or {}
        if info["status"] in ACTIVE or not ev or all("outcomes" in v for v in ev.values()):
            continue
        agents = [a for a in info["config"]["agents"] if a["id"] in ev]
        new = evaluate_run(info["path"], agents, games=next(iter(ev.values()))["games"])
        for aid, v in new.items():
            old = ev[aid]
            same = all(abs(old[k] - v[k]) < 1e-9 for k in ("mean", "median", "max"))
            if verbose:
                print(f"{info['id']} {aid}: mean {old['mean']:.2f} -> {v['mean']:.2f}"
                      + ("" if same else "  (DIFFERENT: the model or the environment changed)"), flush=True)
        update_run(info["path"], evaluation={**ev, **new})
        changed.add(info["lesson"])
    for lesson in changed:
        update_lesson(lesson)
    if changed:
        write_index()
    return sorted(changed)


def evaluate_run(run_dir, agents, games=100):
    from evaluate import evaluate
    out = {}
    for a in agents:
        path = model_path(run_dir, a)
        if os.path.exists(path):
            try:
                ev = evaluate(path, games)
            except ValueError as e:  # e.g. a jev run that finished no game
                print(f"[lessons] {a['id']}: not evaluated ({e})", flush=True)
                continue
            out[a["id"]] = {k: ev[k] for k in EVAL_KEYS}
    return out


def finish_run(run_dir, status="finished", eval_games=100):
    info = read_run(run_dir)
    agents = info["config"]["agents"]
    fields = {"status": status, "finished": time.strftime("%Y-%m-%d %H:%M:%S"),
              "final": final_stats(run_dir, agents)}
    if eval_games:
        fields["evaluation"] = evaluate_run(run_dir, agents, eval_games)
    info = update_run(run_dir, **fields)
    write_json(os.path.join(run_dir, "run.json"), scrub_info(info))  # the pid is no longer needed
    update_lesson(info["lesson"])
    write_index()
    return read_run(run_dir)


def import_run(config, results_dir, models_dir, eval_games=100):
    """Record a run that was trained without the dashboard (copies its CSVs and models)."""
    config = runconfig.normalize(config)
    run_dir = new_run(config, status="finished")
    for a in config["agents"]:
        for src, sub, name in ((results_dir, "results", f"{a['id']}.csv"),
                               (models_dir, "models", os.path.basename(model_path(run_dir, a))),
                               (models_dir, "models", f"{a['id']}_best.json")):
            if os.path.exists(os.path.join(src, name)):
                shutil.copy2(os.path.join(src, name), os.path.join(run_dir, sub, name))
    return finish_run(run_dir, "finished", eval_games)


