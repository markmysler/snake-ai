LIVE_ROOT = os.path.join(tempfile.gettempdir(), "snake-ai-live")
START, END = "<!-- RESULTS:START (generated by lessons.py - edits here are overwritten) -->", "<!-- RESULTS:END -->"
ASTART, AEND = "<!-- ANALYSIS:START (AI analysis, generated by lessons.py - edits here are overwritten) -->", "<!-- ANALYSIS:END -->"
ACTIVE = ("queued", "running")
MAX_SEEDS = 10

TEMPLATE = """# {lesson}

**Question:** _What do you want to find out?_

**Change:** _What is different from the previous lesson? Change one thing at a time,
otherwise you cannot tell which change caused the result._

**Prediction:** _What do you expect, and why? Write it down before looking at the results._

## Results

{start}
{end}

## What we learned

_Fill this in after watching the dashboard and reading the table above._
"""


# ---- files ----------------------------------------------------------------------
def read_json(path, default=None):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return default


def write_json(path, obj):
    tmp = f"{path}.{os.getpid()}.tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=2)
    os.replace(tmp, path)


def run_path(run_id):
    lesson, _, rid = str(run_id).partition("/")
    if not lesson or not rid or runconfig.slug(lesson) != lesson or "/" in rid or ".." in rid:
        raise ValueError(f"bad run id {run_id!r}")
    return os.path.join(LESSONS_DIR, lesson, "runs", rid)


def live_dir(run_id):
    return os.path.join(LIVE_ROOT, run_id.replace("/", "__"))


def model_path(run_dir, agent):
    return os.path.join(run_dir, "models", f"{agent['id']}_best.{ALGORITHMS[agent['algorithm']].model_ext}")


