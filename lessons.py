def ensure_lesson(lesson):
    path = os.path.join(LESSONS_DIR, lesson, "LESSON.md")
    if not os.path.exists(path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(TEMPLATE.format(lesson=lesson, start=START, end=END))


def lesson_title(lesson):
    try:
        with open(os.path.join(LESSONS_DIR, lesson, "LESSON.md"), encoding="utf-8") as f:
            return f.readline().strip().lstrip("# ").strip() or lesson
    except OSError:
        return lesson


def run_table(info):
    from evaluate import format_table
    rows = []
    for a in info["config"]["agents"]:
        st, ev = info.get("final", {}).get(a["id"]), info.get("evaluation", {}).get(a["id"], {})
        if not st:
            continue
        rows.append({"agent": a["id"], "progress": f"{st['iteration_label']} {st['iteration']:,}",
                     "steps": f"{st['total_steps']:,}", "games": f"{st['total_games']:,}",
                     "best": st["best_score"], "mean100": st["mean_score_100"],
                     "ev": f"{ev['mean']:.2f} / {ev['median']:.1f} / {ev['max']}" if ev else "-",
                     "evsteps": f"{ev['mean_steps']:.0f}" if ev else "-",
                     "ends": "/".join(str(ev["outcomes"][k]) for k in ("wall", "body", "starved", "won"))
                     if ev.get("outcomes") else "-"})
    cols = [("agent", "agent", "{}"), ("progress", "progress", "{}"), ("env steps", "steps", "{}"),
            ("games", "games", "{}"), ("best (train)", "best", "{}"), ("mean100 (train)", "mean100", "{:.2f}"),
            ("eval mean / median / max", "ev", "{}"), ("eval steps/game", "evsteps", "{}"),
            ("eval ends wall/body/starved/won", "ends", "{}")]
    return format_table(rows, cols) if rows else "(no stats recorded)"


def describe_run(info):
    c, mach = info["config"], info.get("machine", {})
    d = runconfig.describe(c)
    budget = f"{c['time_budget_min']:g} min" if c["time_budget_min"] else "until stopped"
    power = " · on battery" if mach.get("on_battery") else ""
    agents = ", ".join(f"{a['id']} ({a['reward']})" if c["reward"] is None else a["id"] for a in d["agents"])
    title = f"### Run `{info['run_id']}`" + (f" · {info['name']}" if info.get("name") else "")
    g = info.get("group")
    if g:
        title += f" · seed {g['index'] + 1} of {g['size']}"
    lines = [f"{title} ({info.get('status', '?')})", "",
             f"vision **{d['vision_spec']}** ({d['inputs']:,} inputs) · reward **{d['reward']}** · "
             f"agents {agents} · grid {c['width']}x{c['height']} · training time {budget} · "
             f"{mach.get('cpus', mach.get('cpu_count', '?'))} logical CPUs{power}", ""]
    if info.get("note"):
        lines += [f"> {info['note']}", ""]
    lines += ["```", run_table(info), "```", "",
              f"Watch it: `python -m dashboard.server` then open **Runs** and pick `{info['id']}`.", ""]
    return "\n".join(lines)


def strip_analysis(text):
    if ASTART in text and AEND in text:
        head, rest = text.split(ASTART, 1)
        text = head.rstrip("\n") + "\n" + rest.split(AEND, 1)[1].lstrip("\n")
    return text


def _md(text):
    """AI-written text, made safe for markdown rendered as HTML (no raw tags)."""
    return str(text or "").strip().replace("<", "&lt;").replace(">", "&gt;")


def describe_analysis(info):
    """The AI analysis of one run as markdown, or "" if it has none."""
    a = read_json(os.path.join(info["path"], "analysis.json"))
    if not a or a.get("state") != "done":
        return ""
    r = a["result"]
    title = f"### Run `{info['run_id']}`" + (f" · {info['name']}" if info.get("name") else "")
    lines = [title, "", f"**{_md(r['headline'])}**", "", _md(r.get("summary")), "",
             f"**Why:** {_md(r.get('diagnosis'))}", "", f"**What we learned:** {_md(r.get('learned'))}", ""]
    if r.get("prediction_check"):
        lines += [f"**Prediction check:** {_md(r['prediction_check'])}", ""]
    recs = [x for x in a.get("recommendations", []) if not x.get("errors")]
    if recs:
        lines.append("**Try next:**")
        for i, x in enumerate(recs, 1):
            change = "; ".join(x.get("changes") or []) or "same recipe"
            launched = f" Launched as {', '.join(f'`{l}`' for l in x['launched'])}." if x.get("launched") else ""
            lines.append(f"{i}. **{_md(x['title'])}** ({_md(change)}). {_md(x['why'])} "
                         f"_Prediction:_ {_md(x['prediction'])}{launched}")
        lines.append("")
    if a.get("ideas"):
        lines += ["**Ideas for the lab** (need new code; see [ideas/IDEAS.md](../../ideas/IDEAS.md)): "
                  + "; ".join(f"{_md(i['title'])} ({i['id']})" for i in a["ideas"]), ""]
    lines += [f"_Written by {a.get('model', 'an LLM')} on {a.get('created', '?')}. AI analyses can be wrong: "
              "check them against the charts in the dashboard._", ""]
    return "\n".join(lines)


def describe_group(group_id, runs):
    members = group_members(group_id, runs)
    size = members[0]["group"]["size"] if members else 0
    done = [m for m in members if m.get("evaluation")]
    lines = [f"### Seed group `{group_id}` ({len(done)} of {size} seeds tested)", "",
             "Same recipe, different seeds. If two recipes' ranges overlap, the difference between them may be luck.", "",
             "| agent | test mean ± std | min – max | seeds |", "|---|---|---|---|"]
    for aid, s in group_spread(done).items():
        std = f" ± {s['std']:.2f}" if s["std"] is not None else ""
        lines.append(f"| {aid} | {s['mean']:.2f}{std} | {s['min']:.2f} – {s['max']:.2f} | {s['n']} |")
    return "\n".join(lines) + "\n"


def update_lesson(lesson):
    """Regenerate the RESULTS block of LESSON.md from all of this lesson's runs, and the ANALYSIS
    block from their AI analyses (the block is removed when there are none)."""
    path = os.path.join(LESSONS_DIR, lesson, "LESSON.md")
    if not os.path.isdir(os.path.dirname(path)):
        return
    ensure_lesson(lesson)
    with open(path, encoding="utf-8") as f:
        text = f.read()
    all_runs = list_runs()
    runs = [r for r in all_runs if r["lesson"] == lesson and r["status"] not in ACTIVE]
    block = "\n".join([*(describe_group(gid, all_runs) for gid in dict.fromkeys(
        r["group"]["id"] for r in runs if r.get("group"))), *(describe_run(r) for r in runs)]) or "_No runs yet._\n"
    text = strip_analysis(text)
    if START in text and END in text:
        head, rest = text.split(START, 1)
        text = head + START + "\n" + block + rest[rest.index(END):]
    else:
        text += f"\n## Results\n\n{START}\n{block}{END}\n"
    analyses = "\n".join(filter(None, (describe_analysis(r) for r in runs)))
    if analyses:
        head, rest = text.split(END, 1)
        text = f"{head}{END}\n\n{ASTART}\n## AI analysis\n\n{analyses}{AEND}\n{rest}"
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def lessons():
    if not os.path.isdir(LESSONS_DIR):
        return []
    return sorted(d for d in os.listdir(LESSONS_DIR) if os.path.isfile(os.path.join(LESSONS_DIR, d, "LESSON.md")))


def write_index():
    import course
    os.makedirs(LESSONS_DIR, exist_ok=True)
    runs = list_runs()
    in_course = [lesson for lesson in course.lessons_in_order() if lesson in lessons()]
    lines = ["# Lessons", "",
             "Each folder is one experiment: a question, one change, the runs that answer it, and the",
             "models those runs produced. This file is regenerated by `lessons.py`.", "",
             "Eval = each agent's saved best model playing 100 fixed-seed games (mean apples). "
             "Numbers are from the latest finished run of each lesson.", ""]
    head = ["| Lesson | Runs | Latest: vision | reward | eval by agent |", "|---|---|---|---|---|"]
    if in_course:
        lines += ["## The course", "", "Start here and read the lessons in order (see `course.py`).", "", *head,
                  *(_index_row(lesson, runs) for lesson in in_course),
                  "", "## Notebook", "", "Earlier experiments, kept as they were run. Several were pilots for the course.", ""]
    lines += [*head, *(_index_row(lesson, runs) for lesson in lessons() if lesson not in in_course)]
    with open(os.path.join(LESSONS_DIR, "README.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def _index_row(lesson, runs):
    lr = [r for r in runs if r["lesson"] == lesson]
    done = [r for r in lr if r.get("evaluation")]
    last = done[-1] if done else None
    if last:
        d = runconfig.describe(last["config"])
        evals = ", ".join(f"{k} {v['mean']:.1f}" for k, v in last["evaluation"].items())
        cells = f"{d['vision_spec']} | {d['reward']} | {evals}"
    else:
        cells = "- | - | -"
    return f"| [{lesson_title(lesson)}]({lesson}/LESSON.md) | {len(lr)} | {cells} |"


# ---- CLI ----------------------------------------------------------------------
def main():
    import sys
    if sys.argv[1:2] == ["course"]:  # python lessons.py course ... = python course.py ...
        import course
        sys.argv = [sys.argv[0], *sys.argv[2:]]
        return course.main()
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list")
    sub.add_parser("index")
    sub.add_parser("backfill", help="re-test old runs to add how each test game ended")
    sub.add_parser("scrub", help="drop machine-specific details (paths, OS, RAM) from recorded runs")
    ev = sub.add_parser("evaluate")
    ev.add_argument("run", help="<lesson>/<run-id>")
    ev.add_argument("--games", type=int, default=100)
    de = sub.add_parser("delete")
    de.add_argument("run", help="<lesson>/<run-id>")
    im = sub.add_parser("import")
    im.add_argument("lesson")
    im.add_argument("--results", default="results")
    im.add_argument("--models", default="models")
    im.add_argument("--vision", default="short")
    im.add_argument("--reward", default="score")
    im.add_argument("--agents", default="ga,dqn", help="agent ids = algorithm names, comma separated")
    im.add_argument("--name", default="")
    a = p.parse_args()

    if a.cmd == "list":
        for r in list_runs():
            ev = r.get("evaluation", {})
            print(f"{r['id']:45s} {r['status']:11s} {runconfig.describe(r['config'])['vision_spec']:16s} "
                  + "  ".join(f"{k}={v['mean']:.1f}" for k, v in ev.items()))
    elif a.cmd == "scrub":
        print(f"{len(scrub())} file(s) scrubbed")
    elif a.cmd == "backfill":
        print("updated lessons:", ", ".join(backfill()) or "none (every run already has outcomes)")
    elif a.cmd == "index":
        for lesson in lessons():
            update_lesson(lesson)
        write_index()
    elif a.cmd == "evaluate":
        print(run_table(finish_run(run_path(a.run), read_run(run_path(a.run))["status"], a.games)))
    elif a.cmd == "delete":
        delete_run(a.run)
        print(f"deleted {a.run}")
    elif a.cmd == "import":
        info = import_run({"lesson": a.lesson, "name": a.name, "vision": a.vision, "reward": a.reward,
                           "agents": a.agents.split(","), "time_budget_min": 0}, a.results, a.models)
        print(f"recorded {info['id']}\n{run_table(info)}")


if __name__ == "__main__":
    main()
