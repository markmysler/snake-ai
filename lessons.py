"""The run library: every experiment, its write-up and the models it produced.

    lessons/
      README.md                        index of all lessons (regenerated)
      <lesson>/LESSON.md               the write-up. Everything outside the RESULTS markers is
                                       yours; the block between them is regenerated from the runs
      <lesson>/runs/<run-id>/run.json  the recipe (config), status, machine, final stats, evaluation
      <lesson>/runs/<run-id>/results/  stats CSVs (what the dashboard charts)
      <lesson>/runs/<run-id>/models/   best model of each agent (playable in the dashboard)
      <lesson>/runs/<run-id>/logs/     trainer output
      <lesson>/runs/<run-id>/analysis.json   AI analysis + recommended next runs (see analysis.py),
                                       summarised in LESSON.md between the ANALYSIS markers

A run's id is "<lesson>/<run-id>". Files a run publishes while training live in the system
temp folder (LIVE_ROOT), not here, so big, fast-changing files never hit a synced folder.

    python lessons.py list
    python lessons.py evaluate <lesson>/<run-id>     # (re)compute the 100-game evaluation
    python lessons.py delete <lesson>/<run-id>
    python lessons.py import <lesson> --results results --models models --vision short --reward score --agents dqn
    python lessons.py index                          # rebuild LESSON.md results blocks + README.md
    python lessons.py scrub                          # drop machine-specific details before sharing
    python lessons.py course ...                     # the course (see course.py)

What a run records about the machine is only what is needed to judge its results: how many CPUs it
had, whether it ran on battery, how many runs shared it, and the cores and settings each agent
actually used. Nothing that identifies the machine (paths, user name, OS build, RAM) is kept.
"""
